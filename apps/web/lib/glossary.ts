/**
 * Finance glossary for the terms the six screens show: REWIND, DECISION, CASCADE, REVEAL, RESEARCH and
 * LIVE EXPLORE (issue #87).
 *
 * The key is the display title. `uiLabels` holds the exact on-screen text, character for character, copied from
 * apps/web source, so a tooltip can be looked up by what the screen says. lib/glossary.test.mjs fails if any label
 * no longer appears in apps/web source (outside this file), so labels cannot drift from the screens.
 *
 * Plain words for judges: `short` is at most 15 words (a tooltip), `long` at most 60 words. Formulas cite their
 * docs/MATH_MODEL.md section, which is the source of truth: if a definition here and MATH_MODEL disagree,
 * MATH_MODEL wins and this file is the bug.
 *
 * Every example number is traceable (`source`): a MATH_MODEL §9/§10 value, or a deterministic engine run
 * (core/financials.py, core/evaluator.py, core/research.py, POST /api/optimize, POST /api/decision) on the
 * SYNTHETIC demo business and committed data. Hand-worked or hypothetical arithmetic is labelled ILLUSTRATIVE.
 * Money amounts are US dollars of the fictional demo business. `status` marks features that are not on main yet.
 *
 * docs/GLOSSARY.md is generated from this file and must match it. Nothing here is a computed result for display:
 * screens keep reading every figure from the API.
 */

export type GlossaryScreen = "REWIND" | "DECISION" | "CASCADE" | "REVEAL" | "RESEARCH" | "EXPLORE";

export interface GlossaryEntry {
  /** Exact on-screen text for this term, character for character as in apps/web source. At least one. */
  uiLabels: readonly string[];
  /** Plain definition, at most 15 words. */
  short: string;
  /** Fuller plain-English explanation, at most 60 words. Formulas cite MATH_MODEL sections. */
  long: string;
  /** One worked example, ideally with a number. */
  example: string;
  /** Where the example comes from. */
  source: string;
  /** Screens that show the term (EXPLORE = the LIVE EXPLORE screen). */
  screens: readonly GlossaryScreen[];
  /** docs/MATH_MODEL.md section(s) for the formula, when there is one. */
  mathModel?: string;
  /** Set when the feature behind the term is not on main yet. */
  status?: string;
}

